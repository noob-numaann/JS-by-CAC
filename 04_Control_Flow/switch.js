const month = "March" // we can use numbers and  strings both.

switch (month) {
    case 1:
        console.log("January");
        break;

    case 2:
        console.log("Feb");
        break;

    case "March":
        console.log("March");
        break;
    case "April":
        console.log("April");
        break;

    default:
        console.log("default case match");
        
        break;
}